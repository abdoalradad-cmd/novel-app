CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  pass_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  created_at INTEGER NOT NULL,
  premium_until INTEGER NOT NULL DEFAULT 0,
  avatar TEXT NOT NULL DEFAULT '',
  bio TEXT NOT NULL DEFAULT '',
  links TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS novels (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft',
  is_live INTEGER NOT NULL DEFAULT 0,
  hidden INTEGER NOT NULL DEFAULT 0,
  reject_reason TEXT NOT NULL DEFAULT '',
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  published_at INTEGER,
  d_title TEXT NOT NULL DEFAULT '', d_author TEXT NOT NULL DEFAULT '', d_genre TEXT NOT NULL DEFAULT '',
  d_tags TEXT NOT NULL DEFAULT '[]', d_synopsis TEXT NOT NULL DEFAULT '', d_cover TEXT NOT NULL DEFAULT '', d_extra TEXT NOT NULL DEFAULT '{}',
  l_title TEXT NOT NULL DEFAULT '', l_author TEXT NOT NULL DEFAULT '', l_genre TEXT NOT NULL DEFAULT '',
  l_tags TEXT NOT NULL DEFAULT '[]', l_synopsis TEXT NOT NULL DEFAULT '', l_cover TEXT NOT NULL DEFAULT '', l_extra TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_novels_user ON novels(user_id);
CREATE INDEX IF NOT EXISTS idx_novels_status ON novels(status, is_live);
CREATE TABLE IF NOT EXISTS chapters (
  novel_id INTEGER NOT NULL,
  ver TEXT NOT NULL,
  idx INTEGER NOT NULL,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  locked INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (novel_id, ver, idx)
);
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS attempts (k TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_attempts ON attempts(k, ts);
CREATE TABLE IF NOT EXISTS follows (follower_id INTEGER NOT NULL, author_id INTEGER NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY (follower_id, author_id));
CREATE INDEX IF NOT EXISTS idx_follows_author ON follows(author_id);
CREATE TABLE IF NOT EXISTS reads (k TEXT PRIMARY KEY, n INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS events (id INTEGER PRIMARY KEY AUTOINCREMENT, author_id INTEGER NOT NULL, kind TEXT NOT NULL, novel_id INTEGER NOT NULL, title TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_events_ts ON events(ts);

CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY AUTOINCREMENT, uid INTEGER NOT NULL, kind TEXT NOT NULL, novel_ref TEXT NOT NULL, who TEXT NOT NULL, title TEXT NOT NULL, text TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_notes_uid ON notes(uid, ts);
